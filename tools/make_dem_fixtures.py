"""Build the small GeoTIFF fixtures the pure-Rust reader is tested on, and what rasterio says about them.

    python tools/make_dem_fixtures.py [--glo30 <path to the full Copernicus GLO-30 tile>]

Needs rasterio (the `[dem]` extra). Writes `crates/owd-format/tests/fixtures/dem/*.tif` and
`expected.json`: for each fixture, what rasterio/GDAL reads (size, geotransform, nodata, EPSG, every
pixel as float64 with nodata kept, and bilinear heights at probe points). The Rust test
`crates/owd-format/tests/geotiff.rs` holds the reader to that file. Synthetic fixtures are generated by
this script (Apache-2.0, same as the repository); the Copernicus clip is cut from a tile you download
yourself and is NOT regenerated without `--glo30`. See `fixtures/dem/README.md`.
"""
from __future__ import annotations

import hashlib
import json
import math
import sys
from pathlib import Path

import numpy as np
import rasterio
from rasterio.transform import Affine
from rasterio.windows import Window

OUT = Path(__file__).resolve().parent.parent / "crates/owd-format/tests/fixtures/dem"


def surface(h, w, seed, scale=40.0):
    """A smooth, hilly float surface with a trough: deterministic, no random generator needed."""
    y, x = np.mgrid[0:h, 0:w].astype("float64")
    z = 100.0 + 0.8 * x - 0.35 * y
    z += scale * np.exp(-(((x - 0.35 * w) / (0.18 * w)) ** 2 + ((y - 0.6 * h) / (0.22 * h)) ** 2))
    z += 6.0 * np.sin(x / 5.0 + seed) * np.cos(y / 7.0 - seed)
    z -= 12.0 * np.exp(-(((y - 0.3 * h) / 3.0) ** 2))
    return z


def write(name, data, transform, crs, **opts):
    path = OUT / name
    tags = opts.pop("tags", {})
    with rasterio.open(path, "w", driver="GTiff", height=data.shape[-2], width=data.shape[-1],
                       count=1 if data.ndim == 2 else data.shape[0], dtype=data.dtype,
                       crs=crs, transform=transform, **opts) as dst:
        dst.write(data, 1) if data.ndim == 2 else dst.write(data)
        if tags:
            dst.update_tags(**tags)
    return path


def plain_tiff(path, z):
    """A valid single-band float32 TIFF with no GeoTIFF tags at all, written by hand."""
    import struct
    h, w = z.shape
    data = z.astype("<f4").tobytes()
    entries = [(256, 4, 1, w), (257, 4, 1, h), (258, 3, 1, 32), (259, 3, 1, 1), (262, 3, 1, 1),
               (273, 4, 1, 8), (277, 3, 1, 1), (278, 4, 1, h), (279, 4, 1, len(data)), (339, 3, 1, 3)]
    ifd = struct.pack("<H", len(entries))
    for tag, typ, n, val in entries:
        ifd += struct.pack("<HHII", tag, typ, n, val) if typ == 4 else struct.pack("<HHIHH", tag, typ, n, val, 0)
    ifd += struct.pack("<I", 0)
    head = b"II" + struct.pack("<HI", 42, 8 + len(data))
    path.write_bytes(head + data + ifd)


def probes(h, w, tr):
    """World points: inside, on pixel centres, between them, at the edge, and off the raster."""
    pts = []
    for fr, fc in [(2.0, 3.0), (0.5, 0.5), (h / 2.0 + 0.3, w / 2.0 - 0.7), (h - 1.5, w - 1.5),
                   (0.0, 0.0), (h - 0.5, w - 0.5), (3.25, w - 2.1), (h + 3.0, 4.0), (-2.0, -2.0)]:
        x, y = tr * (fc, fr)
        pts.append([x, y])
    return pts


def bilinear(z, tr, x, y):
    """Pixel-centre bilinear on the whole raster (the formula of `volumes/raster.py`), NaN outside."""
    col = (x - tr.c) / tr.a - 0.5
    row = (y - tr.f) / tr.e - 0.5
    h, w = z.shape
    c0, r0 = math.floor(col), math.floor(row)
    if not (c0 >= 0 and r0 >= 0 and c0 < w - 1 and r0 < h - 1):
        return float("nan")
    fc, fr = col - c0, row - r0
    return (z[r0, c0] * (1 - fc) * (1 - fr) + z[r0, c0 + 1] * fc * (1 - fr)
            + z[r0 + 1, c0] * (1 - fc) * fr + z[r0 + 1, c0 + 1] * fc * fr)


def tag(x):
    if isinstance(x, float) and math.isnan(x):
        return "float:nan"
    return x


def pixel_hash(z):
    """SHA-256 of every pixel as little-endian float64 in row-major order, a NaN as the quiet NaN
    0x7ff8000000000000: one number that changes if any pixel does."""
    flat = np.where(np.isnan(z), np.nan, z).astype("<f8")
    return hashlib.sha256(flat.tobytes()).hexdigest()


def describe(path):
    with rasterio.open(path) as ds:
        z = ds.read(1).astype("float64")
        tr = ds.transform
        zm = np.where(z == ds.nodata, np.nan, z) if ds.nodata is not None else z
        pts = probes(ds.height, ds.width, tr)
        return {
            "width": ds.width, "height": ds.height, "count": ds.count, "dtype": ds.dtypes[0],
            "geotransform": [tr.a, tr.b, tr.c, tr.d, tr.e, tr.f],
            "nodata": None if ds.nodata is None else tag(float(ds.nodata)),
            "epsg": ds.crs.to_epsg() if ds.crs else None,
            "pixels_sha256": pixel_hash(z),
            "first_row": [tag(float(v)) for v in z[0]],
            "last_row": [tag(float(v)) for v in z[-1]],
            "probes": [{"x": x, "y": y, "z": tag(float(bilinear(zm, tr, x, y)))} for x, y in pts],
        }


def main(argv):
    OUT.mkdir(parents=True, exist_ok=True)
    expected = {}
    utm = rasterio.crs.CRS.from_epsg(32630)
    t30 = Affine(30.0, 0.0, 580000.0, 0.0, -30.0, 580000.0)

    # stripped, uncompressed float32
    write("f32_strip_none.tif", surface(40, 56, 1).astype("float32"), t30, utm, compress="none")
    # tiled, DEFLATE with the floating-point predictor (3)
    write("f32_tiled_deflate_pred3.tif", surface(70, 100, 2).astype("float32"), t30, utm, tiled=True,
          blockxsize=32, blockysize=32, compress="deflate", predictor=3)
    # stripped, DEFLATE, no predictor, odd rows per strip
    write("f32_strip_deflate.tif", surface(37, 45, 3).astype("float32"), t30, utm, compress="deflate",
          blockysize=5)
    # int16, LZW with the horizontal predictor (2), nodata -32768
    z16 = np.round(surface(48, 64, 4)).astype("int16")
    z16[5:9, 10:20] = -32768
    write("i16_strip_lzw_pred2_nodata.tif", z16, t30, utm, compress="lzw", predictor=2, nodata=-32768)
    # int16 tiled LZW, no predictor, a raster that is not a whole number of tiles
    write("i16_tiled_lzw.tif", np.round(surface(50, 71, 5)).astype("int16"), t30, utm, tiled=True,
          blockxsize=16, blockysize=16, compress="lzw")
    # float32 with a NaN nodata
    zn = surface(30, 40, 6).astype("float32")
    zn[10:14, 5:9] = np.nan
    write("f32_nan_nodata.tif", zn, t30, utm, compress="deflate", nodata=float("nan"))
    # float32 with a finite nodata, web mercator (the parity cases' CRS)
    zf = surface(32, 48, 7).astype("float32")
    zf[0:3, :] = -9999.0
    write("f32_mercator_nodata.tif", zf, Affine(25.0, 0, -250000.0, 0, -25.0, 600000.0),
          rasterio.crs.CRS.from_epsg(3857), compress="lzw", predictor=3, nodata=-9999.0)
    # geographic, arc-second pixels
    write("f32_geographic.tif", surface(36, 52, 8).astype("float32"),
          Affine(1 / 3600.0, 0.0, -2.1, 0.0, -1 / 3600.0, 5.3), rasterio.crs.CRS.from_epsg(4326),
          compress="deflate", predictor=3)
    # PixelIsPoint (as the Copernicus tiles are)
    write("f32_pixel_is_point.tif", surface(30, 30, 9).astype("float32"),
          Affine(1 / 3600.0, 0.0, -3.000138888888889, 0.0, -1 / 3600.0, 6.000138888888889),
          rasterio.crs.CRS.from_epsg(4326), compress="deflate", predictor=3,
          tags={"AREA_OR_POINT": "Point"})
    # float64, uint16
    write("f64_strip_none.tif", surface(20, 24, 10), t30, utm, compress="none")
    write("u16_strip_deflate_pred2.tif", np.round(surface(22, 26, 11) * 3).astype("uint16"), t30, utm,
          compress="deflate", predictor=2)

    for p in sorted(OUT.glob("*.tif")):
        if p.name.startswith(("glo30", "refuse_")):
            continue
        expected[p.name] = describe(p)

    # refusals: files the reader must not misread
    z = surface(24, 32, 12).astype("float32")
    write("refuse_zstd.tif", z, t30, utm, compress="zstd")
    write("refuse_packbits.tif", z, t30, utm, compress="packbits")
    write("refuse_two_bands.tif", np.stack([z, z + 1]), t30, utm, compress="deflate")
    write("refuse_rotated.tif", z, Affine(30.0, 6.0, 580000.0, 6.0, -30.0, 580000.0), utm,
          compress="deflate")
    plain_tiff(OUT / "refuse_no_georef.tif", z)

    if "--glo30" in argv:
        src = Path(argv[argv.index("--glo30") + 1])
        clip(src)
    gl = OUT / "glo30_n05_w003_clip.tif"
    if gl.exists():
        expected[gl.name] = describe(gl)

    (OUT / "expected.json").write_text(json.dumps(expected, indent=1) + "\n", encoding="utf-8")
    print("wrote", len(expected), "fixtures and expected.json to", OUT)


def clip(src):
    """A 80 x 80 pixel window of a Copernicus GLO-30 tile, written with the same georeferencing."""
    with rasterio.open(src) as ds:
        win = Window(1500, 1700, 80, 80)
        data = ds.read(1, window=win)
        tr = ds.window_transform(win)
        path = OUT / "glo30_n05_w003_clip.tif"
        with rasterio.open(path, "w", driver="GTiff", height=80, width=80, count=1, dtype="float32",
                           crs=ds.crs, transform=tr, tiled=True, blockxsize=32, blockysize=32,
                           compress="deflate", predictor=3) as dst:
            dst.write(data, 1)
            dst.update_tags(AREA_OR_POINT="Point")


if __name__ == "__main__":
    main(sys.argv[1:])
